/** Fundamental arguments of the lunar theory, degrees (Meeus 47.1–47.6). */
export function lunarArguments(T) {
  const T2 = T * T, T3 = T2 * T, T4 = T3 * T;
  return {
    Lp: 218.3164477 + 481267.88123421 * T - 0.0015786 * T2 + T3 / 538841 - T4 / 65194000,
    D: 297.8501921 + 445267.1114034 * T - 0.0018819 * T2 + T3 / 545868 - T4 / 113065000,
    M: 357.5291092 + 35999.0502909 * T - 0.0001536 * T2 + T3 / 24490000,
    Mp: 134.9633964 + 477198.8675055 * T + 0.0087414 * T2 + T3 / 69699 - T4 / 14712000,
    F: 93.2720950 + 483202.0175233 * T - 0.0036539 * T2 - T3 / 3526000 + T4 / 863310000,
    A1: 119.75 + 131.849 * T,
    A2: 53.09 + 479264.290 * T,
    A3: 313.45 + 481266.484 * T,
    E: 1 - 0.002516 * T - 0.0000074 * T2,
  };
}

/**
 * Geocentric ecliptic position of the Moon, mean equinox of date.
 * @returns {{lonDeg:number, latDeg:number, distanceKm:number}}
 */
export function moonEcliptic(T) {
  const a = lunarArguments(T);
  const D = a.D * DEG, M = a.M * DEG, Mp = a.Mp * DEG, F = a.F * DEG;

  let sumL = 0, sumR = 0, sumB = 0;

  for (const [cd, cm, cmp, cf, cl, cr] of TERMS_LR) {
    const arg = cd * D + cm * M + cmp * Mp + cf * F;
    const e = cm === 0 ? 1 : (Math.abs(cm) === 1 ? a.E : a.E * a.E);
    sumL += cl * e * Math.sin(arg);
    sumR += cr * e * Math.cos(arg);
  }
  for (const [cd, cm, cmp, cf, cb] of TERMS_B) {
    const arg = cd * D + cm * M + cmp * Mp + cf * F;
    const e = cm === 0 ? 1 : (Math.abs(cm) === 1 ? a.E : a.E * a.E);
    sumB += cb * e * Math.sin(arg);
  }

  // Additive terms from Venus, Jupiter and the flattening of the Earth.
  sumL += 3958 * Math.sin(a.A1 * DEG)
        + 1962 * Math.sin((a.Lp - a.F) * DEG)
        + 318 * Math.sin(a.A2 * DEG);
  sumB += -2235 * Math.sin(a.Lp * DEG)
        + 382 * Math.sin(a.A3 * DEG)
        + 175 * Math.sin((a.A1 - a.F) * DEG)
        + 175 * Math.sin((a.A1 + a.F) * DEG)
        + 127 * Math.sin((a.Lp - a.Mp) * DEG)
        - 115 * Math.sin((a.Lp + a.Mp) * DEG);

  return {
    lonDeg: (((a.Lp + sumL / 1e6) % 360) + 360) % 360,
    latDeg: sumB / 1e6,
    distanceKm: 385000.56 + sumR / 1000,
  };
}
